#!/usr/bin/env node
/**
 * Regenerates docs/migration/prompt-prefix.md: the byte-identical prefix that every
 * AIDLC task prompt for this repo must start with so that Claude prompt caching hits.
 *
 * Usage: node scripts/aidlc-prompt-prefix.mjs [--check]
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname.replace(/\/$/, '');
const target = join(root, 'docs/migration/prompt-prefix.md');

const IGNORED = new Set(['node_modules', '.git', 'dist', '.angular', 'out-tsc', 'test-results', 'playwright-report']);

function tree(dir) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    if (IGNORED.has(name)) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      out.push(`${relative(root, full)}/`, ...tree(full));
    } else {
      out.push(relative(root, full));
    }
  }
  return out;
}

const file = (p) => readFileSync(join(root, p), 'utf8').trimEnd();

const conventions = `- Angular 20, standalone components only; no NgModules.
- Templates use block control flow (@if / @for with track / @switch); structural
  directives (*ngIf, *ngFor, *ngSwitch) must not be reintroduced.
- Dependencies are injected with inject(); no constructor parameter injection.
- Styles are SCSS; use @use "sass:math" instead of / for division.
- Lint is angular-eslint via .eslintrc.json; TSLint and codelyzer are removed.
- Unit tests are Karma + Jasmine (ChromeHeadlessNoSandbox); e2e is Playwright in e2e/.
- Build uses @angular/build:application; browser output is dist/angular-hnpwa/browser.
- Node ^20.19 || ^22.12 || ^24; package manager is npm with legacy-peer-deps=true.
- Angular upgrades are strictly sequential, one major at a time, via
  ng update @angular/core@N @angular/cli@N.`;

const body = `<!-- GENERATED by scripts/aidlc-prompt-prefix.mjs - do not edit by hand. -->
# AIDLC stable prompt prefix

Every task prompt in this migration programme starts with the exact bytes below and
appends only the task-specific instruction at the end. Keeping this block byte-identical
lets Anthropic prompt caching serve it as \`cache_read_input_tokens\` on every task after
the first, which is what the AIDLC cost table measures.

## Repository

infosys-training/angular2-hn - a progressive Hacker News client built with Angular.

## package.json

\`\`\`json
${file('package.json')}
\`\`\`

## angular.json

\`\`\`json
${file('angular.json')}
\`\`\`

## tsconfig.json

\`\`\`json
${file('tsconfig.json')}
\`\`\`

## tsconfig.app.json

\`\`\`json
${file('tsconfig.app.json')}
\`\`\`

## tsconfig.spec.json

\`\`\`json
${file('tsconfig.spec.json')}
\`\`\`

## File tree

\`\`\`
${tree(root).join('\n')}
\`\`\`

## Conventions

${conventions}

## Task

<!-- Only the text after this heading varies between tasks. -->
`;

if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8');
  if (current !== body) {
    console.error(`${relative(root, target)} is stale; run node scripts/aidlc-prompt-prefix.mjs`);
    process.exit(1);
  }
  console.log('prompt prefix is up to date');
} else {
  writeFileSync(target, body);
  console.log(`wrote ${relative(root, target)} (${Buffer.byteLength(body)} bytes)`);
}
